import axios from 'axios';
import React, { useEffect, useState } from 'react'
import { backEndUrl } from '../App';
import moment from 'moment';
import Description from './Description';
import Report from './Report';
import { jsPDF } from "jspdf";

function HistoryComponent() {

    const [sessions, setSessions] = useState([]);
    const [visible, setVisible] = useState(false);
    const [reportVisible, setReportVisible] = useState(false);
    const [selectedSession, setSelectedSession] = useState(null);

    const planLevel = {
        'Free': 0,
        'Pro': 1,
        'Premium': 2
    }

    const handleVisibility = () => {
        setVisible(!visible);
    }

    const handleReportVisibility = (e, session) => {
        e.preventDefault();
        setReportVisible(!visible);
        setSelectedSession(session);
    }

    const getSessions = async () => {

        try {
            const response = await axios.get(backEndUrl + '/api/session/getallsessions', {
                withCredentials: true
            })
            console.log(response.data)
            if (response.data.success) {
                setSessions(response.data.sessions);
            }
        }
        catch (error) {
            console.log(error);
        }
    }

    useEffect(() => {
        getSessions();

    }, []);




    const downloadReport = (session) => {

        const report = session.session.report;

        const doc = new jsPDF();

        let y = 20;

        // Title
        doc.setFont("helvetica", "bold");
        doc.setFontSize(20);
        doc.text("Medivoice AI Consultation Report", 105, y, { align: "center" });

        y += 15;

        // Divider
        doc.line(20, y, 190, y);
        y += 10;

        doc.setFontSize(12);
        doc.setFont("helvetica", "normal");

        doc.text(`Patient: ${report.user}`, 20, y);
        y += 8;

        doc.text(`Doctor: ${report.agent}`, 20, y);
        y += 8;

        doc.text(
            `Date: ${moment(report.timestamp).format("DD MMM YYYY, hh:mm A")}`,
            20,
            y
        );
        y += 12;

        doc.line(20, y, 190, y);

        y += 10

        // Chief Complaint
        doc.setFont("helvetica", "bold");
        doc.text("Chief Complaint", 20, y);
        y += 8;

        doc.setFont("helvetica", "normal");
        const complaint = doc.splitTextToSize(report.chiefComplaint || "-", 170);
        doc.text(complaint, 20, y);
        y += complaint.length * 7 + 5;

        doc.line(20, y, 190, y);

        y += 10

        // Summary
        doc.setFont("helvetica", "bold");
        doc.text("Consultation Summary", 20, y);
        y += 8;

        doc.setFont("helvetica", "normal");
        const summary = doc.splitTextToSize(report.summary || "-", 170);
        doc.text(summary, 20, y);
        y += summary.length * 7 + 5;

        doc.line(20, y, 190, y);

        y += 10

        // Symptoms
        doc.setFont("helvetica", "bold");
        doc.text("Symptoms", 20, y);
        y += 8;

        doc.setFont("helvetica", "normal");

        if (report.symptoms.length) {
            report.symptoms.forEach((item) => {
                doc.text(`• ${item}`, 25, y);
                y += 7;
            });
        } else {
            doc.text("No symptoms recorded.", 25, y);
            y += 7;
        }

        y += 5;

        doc.line(20, y, 190, y);

        y += 10

        // Recommendations
        doc.setFont("helvetica", "bold");
        doc.text("Recommendations", 20, y);
        y += 8;

        doc.setFont("helvetica", "normal");

        report.recommendations.forEach((item) => {
            const lines = doc.splitTextToSize(`• ${item}`, 165);
            doc.text(lines, 25, y);
            y += lines.length * 7;
        });

        y += 10;

        // Disclaimer
        doc.setDrawColor(180);

        doc.line(20, y, 190, y);
        y += 10;

        doc.setFontSize(10);
        doc.setTextColor(120);

        const disclaimer = doc.splitTextToSize(
            "This report was generated by an AI Medical Assistant and is intended for informational purposes only. It is not a substitute for professional medical advice, diagnosis, or treatment. Please consult a licensed healthcare provider for any medical concerns.",
            170
        );

        doc.text(disclaimer, 20, y);

        doc.save(
            `Medical_Report_${moment(report.timestamp).format("DD-MM-YYYY")}.pdf`
        );
    };


    return (
        <div className='w-full p-5 mt-20 px-30 max-lg:px-20 max-md:px-5'>
            <div className="flex justify-between items-center py-8 ">
                <h1 className='text-black text-2xl font-bold'>My Dashboard</h1>
                <button className='bg-black text-white p-3 px-4 text-[15px] font-semibold rounded-xl hover:cursor-pointer hover:bg-gray-800 transition-all duration-300 max-sm:hidden' onClick={handleVisibility}>+ Consult With Doctor</button>
            </div>
            <div className="overflow-x-auto">
                <table className='w-full p-5 min-w-[800px]'>
                    <thead>
                        <tr className=''>
                            <th className='w-1/5 text-start py-4'>AI Medical Specilist</th>
                            <th className='w-1/5 text-start'>Description</th>
                            <th className='w-1/5 text-start'>Date</th>
                            <th className='w-1/5 text-start'>Report</th>
                            <th className='w-1/5 text-end'></th>
                        </tr>
                    </thead>
                    <tbody>
                        {
                            sessions.map((ses, index) => (
                                <tr className='border-t border-gray-300 hover:bg-gray-200 px-2' key={index}>
                                    <td className='w-1/4 text-start py-4'>{ses.doctor.specialization}</td>
                                    <td className='w-1/4 text-start'>{ses.session.note}</td>
                                    <td className='w-1/4 text-start'>{moment(new Date(ses.session.report?.timestamp)).fromNow()}</td>
                                    <td className='w-1/4 text-start'><button className='font-semibold hover:border-b-[1px] hover:cursor-pointer disabled:hidden' onClick={(e) => handleReportVisibility(e, ses)} disabled={!ses.session.report}>View Report</button></td>
                                    <td className='w-1/4 text-end'><button
                                        className='font-semibold hover:border-b-[1px] hover:cursor-pointer disabled:text-gray-300'
                                        onClick={() => downloadReport(ses)}
                                        disabled={!ses.session.report || planLevel[ses.plan] < 1}
                                    >
                                        Download
                                    </button></td>
                                </tr>
                            ))
                        }

                    </tbody>
                </table>
            </div>

            {
                visible ?
                    <Description handleVisibility={handleVisibility} visible={visible} /> : ""
            }

            {
                reportVisible ?
                    <Report setReportVisible={setReportVisible} reportVisible={reportVisible} session={selectedSession} /> : ""
            }
        </div >
    )
}

export default HistoryComponent